/** 定位身份短语（放在主体描述里，帮助模型理解人物的社会身份） */
const ROLE_IDENTITY: Record<Role, string> = {
  猛将: '以勇力冲阵的武将',
  统帅: '统领军队的主帅',
  谋士: '运筹策士的智者',
  医者: '悬壶济世的医者',
  器者: '巧夺天工的工匠与学者',
}

/** 组装单个英灵的卡面提示词 */
export function buildCardPrompt(heroId: string, style: StyleKey, format: FormatKey = 'card'): string {
  const entry = ROSTER.find((h) => h.id === heroId)
  if (!entry) throw new Error(`未知英灵：${heroId}`)

  const culture = CULTURE_LOOK[entry.region] ?? CULTURE_LOOK[entry.era] ?? CULTURE_LOOK['中国']
  const detail = (HERO_DETAIL[heroId] ?? culture).replace(/[。.，,、\s]+$/, '')

  return [
    `【主体】${entry.name}，${entry.era}时期的${entry.region}历史人物，身份是${ROLE_IDENTITY[entry.role]}。`,
    `【形象】${detail}。人物为可信的成年人面貌，神情专注而沉着，不做夸张表情。`,
    `【姿态】${ROLE_LOOK[entry.role]}`,
    `【背景】${ELEMENT_LOOK[entry.element].bg}。`,
    `【配色】${ELEMENT_LOOK[entry.element].color}，整体色调统一，背景与人物形成明确的前后层次。`,
    RARITY_LOOK[entry.rarity],
    COMPOSITION[format],
    STYLE_BLOCK[style],
    `【排除】${EXCLUSIONS}`,
  ].join('\n')
}
