/**
 * 校验：生图侧的资源清单与 core 的 `RESOURCE_ICON_KEYS` **完全一致**。
 *
 * 两边各写一套必然对不上——core 声明要出图、生图侧没出，
 * 或者反过来生了一堆没人用的图标（铁律 #4「单一数据源」）。
 *
 * @throws 两边清单不一致时直接抛错（宁可构建失败，也不要静默少图）
 */
export function assertResourceIconCoverage(): void {
  const core = new Set<string>(RESOURCE_ICON_KEYS)
  const tool: readonly string[] = RESOURCE_ICONS.map((r) => r.key)
  const missing = [...core].filter((k) => !tool.includes(k)).sort()
  const extra = tool.filter((k) => !core.has(k)).sort()
  if (missing.length || extra.length) {
    throw new Error(
      `资源图标清单与 core 不一致：缺 ${missing.join(', ') || '无'}；多 ${extra.join(', ') || '无'}`,
    )
  }
}

/**
 * 遍历全部遗物，产出「id → 提示词」映射。
 *
 * 数据直接取 `RELICS` 配置（铁律 #3：新增遗物只加配置，不改逻辑）。
 */
export function buildRelicPrompts(): { id: string; prompt: string }[] {
  return RELICS.map((relic) => {
    const set = RELIC_SET_INDEX.get(relic.setId)
    const stat = (relic.mainStats[0]?.stat ?? 'atk') as StatKey
    return {
      id: relic.id,
      prompt: buildRelicPrompt(relic.id, relic.name, relic.setId, relic.rarity, stat),
    }
  })
}
