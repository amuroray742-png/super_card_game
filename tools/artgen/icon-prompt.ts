/** 按关键词查器形；未命中时按名字兜底（取最后一个两字词当作器物名） */
function lookupForm(name: string): ObjectForm {
  for (const entry of OBJECT_FORMS) {
    if (entry.keys.some((k) => name.includes(k))) return entry.form
  }
  return { form: `一件${name}`, shape: '形制简洁的单件器物，做工精细，轮廓完整清晰' }
}

